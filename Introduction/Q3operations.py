'''Question 3: Write a Java program to enter two numbers and perform addition, subtraction,
 multiplication, division, and modulus.
Asked In Basic program
Input:
Number1 = 20
Number2 = 5

Output:
Addition = 25
Subtraction = 15
Multiplication = 100
Division = 4
Modulus = 0

Explanation:
The program performs all basic arithmetic operations using the two given numbers and displays 
the results.'''

a=int(input("Enter number 1\n"))
b=int(input("Enter number 2\n"))

print("Addition =",a+b)
print("Subtraction =",a-b)
print("Multiplication =",a*b)
print("Division =",a/b)
print("Modulus =",a%b)
print("Float Division =",a//b)
print("Exponential =",a**b)
